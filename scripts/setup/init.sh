#!/usr/bin/env bash
# Create .env with a fresh random value for every secret the lab needs.
#
#   scripts/setup/init.sh           create .env (refuses to overwrite one)
#   scripts/setup/init.sh --force   replace an existing .env
#
# Replacing .env after the stack has run once locks you out of the existing
# data volumes, because the databases keep the old passwords. Remove the
# volumes first with: docker compose down -v
set -euo pipefail

cd "$(dirname "$0")/../.."

if [ -e .env ] && [ "${1:-}" != "--force" ]; then
    echo ".env already exists. Keep it, or run with --force to replace it." >&2
    exit 1
fi

random_hex() {  # random_hex <bytes>
    head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
}

random_uuid() {  # Shuffle only accepts an API key in UUID form
    local hex
    hex="$(random_hex 16)"
    printf '%s-%s-4%s-a%s-%s\n' "${hex:0:8}" "${hex:8:4}" "${hex:13:3}" "${hex:17:3}" "${hex:20:12}"
}

# OpenSearch refuses an admin password without upper case, lower case, a digit and a symbol.
opensearch_password="Aa1-$(random_hex 16)"

umask 077
cat > .env <<ENV
# Generated by scripts/setup/init.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not commit this file.

# Elasticsearch password for the "elastic" user (index for TheHive and Cortex)
ELASTIC_PASSWORD=$(random_hex 24)

# Session secrets
THEHIVE_SECRET=$(random_hex 32)
CORTEX_SECRET=$(random_hex 32)

# Shuffle
SHUFFLE_VERSION=2.3.0
SHUFFLE_OPENSEARCH_PASSWORD=${opensearch_password}
SHUFFLE_DEFAULT_USERNAME=admin
SHUFFLE_DEFAULT_PASSWORD=$(random_hex 16)
SHUFFLE_DEFAULT_APIKEY=$(random_uuid)
SHUFFLE_ENCRYPTION_MODIFIER=$(random_hex 16)

# Accounts that scripts/setup/provision.py creates
THEHIVE_ADMIN_PASSWORD=$(random_hex 16)
THEHIVE_ANALYST_LOGIN=analyst@soc.lab
THEHIVE_ANALYST_PASSWORD=$(random_hex 16)
CORTEX_ADMIN_PASSWORD=$(random_hex 16)
CORTEX_ORGADMIN_PASSWORD=$(random_hex 16)
ENV
chmod 600 .env
echo "Wrote .env with new secrets (file mode 600)."

if [ -r /proc/sys/vm/max_map_count ]; then
    current="$(cat /proc/sys/vm/max_map_count)"
    if [ "$current" -lt 262144 ]; then
        echo
        echo "vm.max_map_count is $current. Elasticsearch and OpenSearch need at least 262144:"
        echo "    sudo sysctl -w vm.max_map_count=262144"
    fi
fi
